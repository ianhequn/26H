# =========================================================
# [常量] 接收端 Wi-Fi 热点
# =========================================================

# 每次关键部署修改后更新该编号，用于判断 SD 卡是否混入了旧文件。
RECEIVER_BUILD_ID = "lckfb-display-v3"

# 板卡冷启动后先等待系统服务、LCD 和 Wi-Fi 驱动稳定。
# 这段等待只影响开机时间，不会增加图传过程中的延迟。
RECEIVER_BOOT_DELAY_S = 5

# 接收端创建的热点名称和密码，必须与发送端 config.py 一致。
AP_SSID = "K230_VIDEO"
AP_PASSWORD = "CHANGE_ME_BEFORE_DEPLOY"

# 固定使用 2.4 GHz 常见信道 6，避免自动信道在部分手机上扫描较慢。
AP_CHANNEL = 6

# config() 启动热点后给底层 Wi-Fi 驱动留出准备时间，单位：秒。
AP_STARTUP_WAIT_S = 2

# 接收端固定 IP、子网掩码和 TCP 监听端口。
RECEIVER_IP = "192.168.8.1"
SUBNET_MASK = "255.255.255.0"
TCP_PORT = 9000

# 同一时刻只需要一个发射设备，等待队列长度设为 1。
TCP_LISTEN_BACKLOG = 1


# =========================================================
# [常量] 接收视频格式
# =========================================================

# 这些参数必须与 transmitter/config.py 完全一致。
# 单位分别为像素、像素、帧/秒。
VIDEO_WIDTH = 640
VIDEO_HEIGHT = 360
VIDEO_FPS = 20


# =========================================================
# [常量] 触摸显示屏
# =========================================================

# 第一版目标硬件：ST7701 800x480 触摸屏。
# 如果实物屏幕不同，只修改这里和 live_decoder.py 的类型映射。
DISPLAY_DRIVER = "ST7701"
DISPLAY_WIDTH = 800
DISPLAY_HEIGHT = 480

# 庐山派官方 LCD 示例使用 to_ide=True。这样物理屏幕显示的同时，CanMV IDE
# 帧缓冲区也能看到输出，便于判断是 LCD 链路还是图像绘制出现问题。
DISPLAY_TO_IDE = True

# Display 初始化后让彩条自检画面保留一小段时间，单位：毫秒。
# 若开机能看到彩条，说明 LCD、Display 和 OSD0 已经正常工作。
DISPLAY_TEST_PATTERN_HOLD_MS = 3000

# 把 640x360 视频居中放置，并在底部保留触摸按钮区域。
# 坐标原点在屏幕左上角，单位：像素。
VIDEO_X = 80
VIDEO_Y = 20

# OSD 状态栏刷新周期，单位：毫秒。
# 视频层由 VDEC 硬件更新，不会跟着 UI 每 250 ms 才刷新。
UI_REFRESH_INTERVAL_MS = 250

# 防止手指按住时重复触发 REC/STOP，单位：毫秒。
TOUCH_DEBOUNCE_MS = 300


# =========================================================
# [常量] 录像
# =========================================================

# 接收端 SD 卡中的录像目录和文件名前缀。
RECORD_DIRECTORY = "/sdcard/records"
RECORD_FILE_PREFIX = "REC"

# 正常触摸控制时保持 False。
# 调试触摸屏之前可以临时改为 True，让每次 TCP 连接后自动开始录像。
AUTO_RECORD_ON_CONNECT = False
